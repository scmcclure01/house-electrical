"""Cache-busting for GitHub Pages (which lets browsers cache files ~10 min).
Rewrites the BUILD block in index.html: versioned stylesheet links, and an import map that
appends ?v=<build> to every ES module so a reload always fetches a matching set of files.
Run automatically by .githooks/pre-commit (enable once with: git config core.hooksPath .githooks)."""
import datetime, json, os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
build = datetime.datetime.now().strftime('%Y%m%d-%H%M%S')
mods = sorted(os.path.relpath(os.path.join(d, f), root).replace(os.sep, '/')
              for d, _, fs in os.walk(os.path.join(root, 'js')) for f in fs if f.endswith('.js'))
imports = {f'./{m}': f'./{m}?v={build}' for m in mods}
block = '\n'.join([
    '<!-- BUILD:start (generated by .githooks/stamp_build.py — do not edit by hand) -->',
    f'  <meta name="build" content="{build}">',
    f'  <link rel="stylesheet" href="css/app.css?v={build}">',
    f'  <link rel="stylesheet" href="css/print.css?v={build}">',
    f'  <script type="importmap">{json.dumps({"imports": imports}, indent=2)}</script>',
    '  <!-- BUILD:end -->',
])
path = os.path.join(root, 'index.html')
html = open(path).read()
new = re.sub(r'<!-- BUILD:start.*?<!-- BUILD:end -->', lambda _: block, html, flags=re.S)
if new == html and 'BUILD:start' not in html:
    raise SystemExit('index.html has no BUILD block')
open(path, 'w').write(new)
print(f'stamped build {build} ({len(mods)} modules)')
